def make_finding(
    rule: Rule,
    *,
    file_path: Optional[str] = None,
    line_number: Optional[int] = None,
    path: Optional[str] = None,
    line: Optional[int] = None,
    file_sha256: Optional[str] = None,
    evidence: str,
    impact: Optional[str] = None,
    suggested_action: Optional[str] = None,
    severity: Optional[Severity] = None,
    confidence: Optional[Confidence] = None,
    branch: Optional[str] = None,
    check_tool: Optional[str] = None,
    reproduced: bool = True,
    sandbox_artifact: bool = False,
    override_title: Optional[str] = None,
    evidence_level: str = "static-only",
    exposure: str = "internal",
    reachability: str = "unknown",
    suppressed: bool = False,
    suppression_reason: Optional[str] = None,
    root_cause_cluster: Optional[str] = None,
    cisa_kev: bool = False,
    epss_score: Optional[float] = None,
) -> Finding:
    """
    Unified factory for creating deterministic, schema-validated Finding instances.
    - Generates stable, reproducible finding ID based on rule ID + location.
    - Restricts CVSS scoring to genuine VULNERABILITY and SECRET findings.
    - Preserves explicit Category and Rule metadata.
    - Computes exposure-weighted priority score for punch-list ordering.
    """
    actual_path = file_path if file_path is not None else path
    actual_line = line_number if line_number is not None else line

    # Deterministic fingerprint-based ID: FIND-{rule_id}-{hash}
    norm_path = (actual_path or "global").replace("\\", "/")
    loc_key = f"{rule.id}:{norm_path}:{actual_line or 0}"
    fingerprint = hashlib.sha1(loc_key.encode("utf-8")).hexdigest()[:8].upper()
    finding_id = f"FIND-{rule.id}-{fingerprint}"

    # Line-independent logical partial fingerprint for SARIF & baseline diffing (excludes line numbers)
    clean_ev = re.sub(r"\s+", " ", evidence.strip())[:80]
    logical_loc_key = f"{rule.id}:{norm_path}:{clean_ev}"
    logical_fingerprint = hashlib.sha256(logical_loc_key.encode("utf-8")).hexdigest()[:16]
    partial_fps = {"logicalLocationKey": logical_fingerprint}

    eff_severity = severity or rule.base_severity
    eff_confidence = confidence or rule.default_confidence
    eff_impact = impact or rule.impact_template
    eff_action = suggested_action or rule.suggested_action
    eff_tool = check_tool or rule.check_tool
    eff_title = override_title or rule.title

    # CVSS estimates MUST NOT be attached to unverified / Possible findings
    # and MUST NOT be attached to policy, hygiene, or correctness findings.
    cvss_score: Optional[float] = None
    cvss_vector: Optional[str] = None
    if rule.category in (FindingCategory.VULNERABILITY, FindingCategory.SECRET):
        if eff_confidence != Confidence.POSSIBLE:
            cvss_score = rule.cvss_score
            cvss_vector = rule.cvss_vector

    # For non-code findings (secrets), default reachability is 1.00 if active/unspecified
    eff_reachability = reachability
    if rule.category == FindingCategory.SECRET and reachability == "unknown":
        eff_reachability = "reachable"

    priority = compute_priority(
        eff_severity,
        eff_confidence,
        reachability=eff_reachability,
        exposure=exposure,
        evidence_level=evidence_level,
        cisa_kev=cisa_kev,
        epss_score=epss_score,
    )

    return Finding(
        id=finding_id,
        rule_id=rule.id,
        category=rule.category,
        title=eff_title,
        severity=eff_severity,
        confidence=eff_confidence,
        provenance="rule",
        status=EvidenceStatus.OBSERVED,
        branch=branch,
        file_path=actual_path,
        line_number=actual_line,
        file_sha256=file_sha256,
        impact=eff_impact,
        evidence=evidence,
        suggested_action=eff_action,
        check_tool=eff_tool,
        cwe_id=rule.cwe_id,
        cwe_name=rule.cwe_name,
        cwe_secondary_ids=list(getattr(rule, "cwe_secondary_ids", ())),
        cvss_score_estimate=cvss_score,
        cvss_vector_estimate=cvss_vector,
        cvss_is_estimate=True,
        environmental_context_assumed="Assumes standard offline air-gap deployment.",
        oracle_origin="static_rule",
        reproduced=reproduced,
        sandbox_artifact=sandbox_artifact,
        owasp_category=rule.owasp_category,
        asvs_chapter=rule.asvs_chapter,
        evidence_level=evidence_level,
        exposure=exposure,
        reachability=eff_reachability,
        priority_score=priority,
        fingerprint=fingerprint,
        partial_fingerprints=partial_fps,
        suppressed=suppressed,
        suppression_reason=suppression_reason,
        root_cause_cluster=root_cause_cluster,
        cisa_kev=cisa_kev,
        epss_score=epss_score,
    )
